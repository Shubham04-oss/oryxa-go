// Package microsoftgraph contains the narrow Microsoft Graph protocol surface
// that cannot safely be delegated to a generic webhook runtime. In particular,
// Graph validates endpoints synchronously and authenticates notifications with
// a subscription-specific clientState rather than an HTTP signature.
package microsoftgraph

import (
	"context"
	"crypto/rand"
	"encoding/base64"
	"encoding/json"
	"errors"
	"fmt"
	"io"
	"net/http"
	"strings"
	"time"

	"github.com/Shubham04-oss/oryxa-go/integrations/internal/piece"
)

const (
	defaultGraphURL = "https://graph.microsoft.com/v1.0"
	maxResponseSize = 1 << 20
	defaultTimeout  = 15 * time.Second
)

var defaultHTTPClient = &http.Client{Timeout: defaultTimeout}

var (
	ErrInvalidSubscription = errors.New("invalid Microsoft Graph subscription")
	ErrGraphRejected       = errors.New("Microsoft Graph rejected subscription request")
)

// RejectionError exposes only Graph's stable error code and HTTP status. It
// intentionally omits the response body, which can contain tenant details.
type RejectionError struct {
	Code       string
	StatusCode int
}

func (e RejectionError) Error() string {
	return fmt.Sprintf("%s: %s (%d)", ErrGraphRejected, e.Code, e.StatusCode)
}

func (e RejectionError) Unwrap() error { return ErrGraphRejected }

// IsAuthorizationRejection reports an access-token/permission rejection
// without requiring callers to parse provider text.
func IsAuthorizationRejection(err error) bool {
	var rejection RejectionError
	return errors.As(err, &rejection) && (rejection.StatusCode == http.StatusUnauthorized || rejection.StatusCode == http.StatusForbidden)
}

// SubscriptionRequest is deliberately restricted to the fields needed for a
// Graph change-notification subscription. The notification URL and client
// state must be generated by the integrations service; callers must never
// accept either value from an end user.
type SubscriptionRequest struct {
	ChangeType               string
	Resource                 string
	NotificationURL          string
	LifecycleNotificationURL string
	ClientState              string
	ExpirationDateTime       time.Time
}

type Subscription struct {
	ID                 string    `json:"id"`
	Resource           string    `json:"resource"`
	ChangeType         string    `json:"changeType"`
	ExpirationDateTime time.Time `json:"expirationDateTime"`
}

// SubscriptionState is the non-secret state that a Graph trigger stores in the
// existing trigger runtime state. clientState is intentionally absent: it is
// held only in the encrypted webhook-route secret, while this state gives
// renew and disable operations the provider subscription ID they require.
type SubscriptionState struct {
	ID        string
	ExpiresAt time.Time
}

const (
	storeSubscriptionID        = "microsoft_graph_subscription_id"
	storeSubscriptionExpiresAt = "microsoft_graph_subscription_expires_at"
)

func (s Subscription) State() SubscriptionState {
	return SubscriptionState{ID: s.ID, ExpiresAt: s.ExpirationDateTime.UTC()}
}

func (s SubscriptionState) StoreMutations() []piece.StoreMutation {
	if !validSubscriptionID(s.ID) || s.ExpiresAt.IsZero() {
		return nil
	}
	return []piece.StoreMutation{
		{Operation: "put", Key: storeSubscriptionID, Value: s.ID},
		{Operation: "put", Key: storeSubscriptionExpiresAt, Value: s.ExpiresAt.UTC().Format(time.RFC3339Nano)},
	}
}

func SubscriptionStateFromStore(store map[string]any) (SubscriptionState, error) {
	if store == nil {
		return SubscriptionState{}, ErrInvalidSubscription
	}
	id, idOK := store[storeSubscriptionID].(string)
	expiresRaw, expiresOK := store[storeSubscriptionExpiresAt].(string)
	expiresAt, err := time.Parse(time.RFC3339Nano, expiresRaw)
	if !idOK || !expiresOK || err != nil || !validSubscriptionID(id) || expiresAt.IsZero() {
		return SubscriptionState{}, ErrInvalidSubscription
	}
	return SubscriptionState{ID: id, ExpiresAt: expiresAt.UTC()}, nil
}

// Client performs the create, renew and remove operations required by Graph.
// It intentionally uses a small HTTP implementation rather than a broad SDK,
// making the request contract testable and preserving the caller's chosen
// access token boundary.
type Client struct {
	HTTPClient *http.Client
	BaseURL    string
	Now        func() time.Time
}

func (c Client) Create(ctx context.Context, accessToken string, request SubscriptionRequest) (Subscription, error) {
	if err := validateCreate(request, c.now()); err != nil {
		return Subscription{}, err
	}
	body, err := json.Marshal(struct {
		ChangeType               string `json:"changeType"`
		Resource                 string `json:"resource"`
		NotificationURL          string `json:"notificationUrl"`
		LifecycleNotificationURL string `json:"lifecycleNotificationUrl,omitempty"`
		ClientState              string `json:"clientState"`
		ExpirationDateTime       string `json:"expirationDateTime"`
	}{
		ChangeType: request.ChangeType, Resource: request.Resource,
		NotificationURL: request.NotificationURL, LifecycleNotificationURL: request.LifecycleNotificationURL,
		ClientState: request.ClientState, ExpirationDateTime: request.ExpirationDateTime.UTC().Format(time.RFC3339Nano),
	})
	if err != nil {
		return Subscription{}, err
	}
	return c.request(ctx, http.MethodPost, "/subscriptions", accessToken, body, http.StatusCreated)
}

func (c Client) Renew(ctx context.Context, accessToken, subscriptionID string, expiration time.Time) (Subscription, error) {
	if !validSubscriptionID(subscriptionID) || expiration.Before(c.now().Add(time.Minute)) {
		return Subscription{}, ErrInvalidSubscription
	}
	body, err := json.Marshal(struct {
		ExpirationDateTime string `json:"expirationDateTime"`
	}{ExpirationDateTime: expiration.UTC().Format(time.RFC3339Nano)})
	if err != nil {
		return Subscription{}, err
	}
	return c.request(ctx, http.MethodPatch, "/subscriptions/"+subscriptionID, accessToken, body, http.StatusOK)
}

// Remove treats Graph's 404 as success. This makes compensation after a
// failed local transaction and trigger teardown idempotent.
func (c Client) Remove(ctx context.Context, accessToken, subscriptionID string) error {
	if !validSubscriptionID(subscriptionID) {
		return ErrInvalidSubscription
	}
	request, err := http.NewRequestWithContext(ctx, http.MethodDelete, c.baseURL()+"/subscriptions/"+subscriptionID, nil)
	if err != nil {
		return err
	}
	request.Header.Set("authorization", "Bearer "+accessToken)
	response, err := c.client().Do(request)
	if err != nil {
		return fmt.Errorf("delete Microsoft Graph subscription: %w", err)
	}
	defer response.Body.Close()
	if response.StatusCode == http.StatusNoContent || response.StatusCode == http.StatusNotFound {
		return nil
	}
	return graphError(response)
}

func (c Client) request(ctx context.Context, method, path, accessToken string, body []byte, success int) (Subscription, error) {
	if strings.TrimSpace(accessToken) == "" {
		return Subscription{}, ErrInvalidSubscription
	}
	request, err := http.NewRequestWithContext(ctx, method, c.baseURL()+path, strings.NewReader(string(body)))
	if err != nil {
		return Subscription{}, err
	}
	request.Header.Set("authorization", "Bearer "+accessToken)
	request.Header.Set("content-type", "application/json")
	response, err := c.client().Do(request)
	if err != nil {
		return Subscription{}, fmt.Errorf("request Microsoft Graph subscription: %w", err)
	}
	defer response.Body.Close()
	if response.StatusCode != success {
		return Subscription{}, graphError(response)
	}
	var subscription Subscription
	decoder := json.NewDecoder(io.LimitReader(response.Body, maxResponseSize+1))
	if err := decoder.Decode(&subscription); err != nil || !validSubscriptionID(subscription.ID) ||
		subscription.ExpirationDateTime.IsZero() {
		return Subscription{}, ErrInvalidSubscription
	}
	return subscription, nil
}

func (c Client) baseURL() string {
	return strings.TrimRight(firstNonEmpty(c.BaseURL, defaultGraphURL), "/")
}

func (c Client) client() *http.Client {
	if c.HTTPClient != nil {
		return c.HTTPClient
	}
	return defaultHTTPClient
}

func (c Client) now() time.Time {
	if c.Now != nil {
		return c.Now().UTC()
	}
	return time.Now().UTC()
}

func graphError(response *http.Response) error {
	body, _ := io.ReadAll(io.LimitReader(response.Body, 8*1024))
	code := "request_failed"
	var payload struct {
		Error struct {
			Code string `json:"code"`
		} `json:"error"`
	}
	if json.Unmarshal(body, &payload) == nil && validErrorCode(payload.Error.Code) {
		code = payload.Error.Code
	}
	return RejectionError{Code: code, StatusCode: response.StatusCode}
}

func validErrorCode(value string) bool {
	if value == "" || len(value) > 80 {
		return false
	}
	for _, character := range value {
		if (character < 'a' || character > 'z') && (character < 'A' || character > 'Z') &&
			(character < '0' || character > '9') && character != '_' && character != '-' && character != '.' {
			return false
		}
	}
	return true
}

func validateCreate(request SubscriptionRequest, now time.Time) error {
	if !validIdentifier(request.ChangeType, 128) || !validResource(request.Resource) ||
		!validHTTPSURL(request.NotificationURL) ||
		(request.LifecycleNotificationURL != "" && !validHTTPSURL(request.LifecycleNotificationURL)) ||
		len(request.ClientState) < 32 || len(request.ClientState) > 128 ||
		request.ExpirationDateTime.Before(now.Add(time.Minute)) {
		return ErrInvalidSubscription
	}
	return nil
}

func NewClientState(source io.Reader) (string, error) {
	if source == nil {
		source = rand.Reader
	}
	bytes := make([]byte, 32)
	if _, err := io.ReadFull(source, bytes); err != nil {
		return "", fmt.Errorf("generate Microsoft Graph client state: %w", err)
	}
	return base64.RawURLEncoding.EncodeToString(bytes), nil
}

func validIdentifier(value string, maximum int) bool {
	return value != "" && len(value) <= maximum && strings.TrimSpace(value) == value && !strings.ContainsAny(value, "\r\n\t")
}

func validSubscriptionID(value string) bool {
	if value == "" || len(value) > 512 {
		return false
	}
	for _, character := range value {
		if (character < 'a' || character > 'z') && (character < 'A' || character > 'Z') &&
			(character < '0' || character > '9') && character != '_' && character != '-' && character != '.' {
			return false
		}
	}
	return true
}

func validResource(value string) bool {
	return validIdentifier(value, 2048) && strings.HasPrefix(value, "/") && !strings.Contains(value, "//")
}

func validHTTPSURL(value string) bool {
	request, err := http.NewRequest(http.MethodGet, value, nil)
	return err == nil && request.URL.Scheme == "https" && request.URL.Host != "" && request.URL.User == nil && request.URL.Fragment == ""
}

func firstNonEmpty(values ...string) string {
	for _, value := range values {
		if value != "" {
			return value
		}
	}
	return ""
}
